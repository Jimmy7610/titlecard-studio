test("a PNG sequence too large to deliver is refused before it starts", async ({ page }) => {
  await gotoEditor(page);
  await openExport(page);

  await page.getByRole("tab", { name: "Frames" }).click();

  const set = async (id: string, value: string) => {
    await page.locator(`#${id}`).fill(value);
    await page.locator(`#${id}`).press("Enter");
  };
  await set("frames-width", "3840");
  await set("frames-height", "2160");
  await set("frames-fps", "60");
  await set("frames-duration", "30");

  // A frame cap bounds nothing on its own; the budget is in bytes.
  await expect(page.getByText(/Too large/)).toBeVisible();
  await expect(page.getByRole("button", { name: /Export \d+ PNGs/ })).toBeDisabled();

  await set("frames-width", "640");
  await set("frames-height", "360");
  await set("frames-duration", "1");
  await expect(page.getByRole("button", { name: /Export \d+ PNGs/ })).toBeEnabled();
});
